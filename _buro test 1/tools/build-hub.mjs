#!/usr/bin/env node
// Builds the PORTAL — index.html in the project root — from variants.json.
//
//   node tools/build-hub.mjs      or      npm run hub
//
// Double-click index.html in the file tree and you are looking at every version
// with a picture of each. It needs no server and no build: the previews are read
// from previews/ beside it, and every link goes to the DEPLOYED copy, so it works
// offline-authored and online-clicked. A portal that only resolves while a dev
// server happens to be running is a portal you cannot use from the file tree,
// which is the one place it was asked to live.
//
// The site itself is index1.html. The portal took the index.html name because
// that is the file a person clicks without being told to.
//
// The copy at the root of gh-pages is generated by deploy.mjs from this same
// template, so the two cannot drift.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { buildHub, previewFor } from './hub.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const REGISTER = JSON.parse(readFileSync(join(ROOT, 'variants.json'), 'utf8'));
const BASE = REGISTER.base.replace(/\/+$/, '') + '/';
const ORIGIN = 'https://sigovs.github.io';

// "Live" means published, and it is asked of the branch rather than assumed: a
// portal that offers a deploy which is not there sends you to a 404.
//
// The ref is FETCHED first. Reading origin/gh-pages without that reports nothing
// on any clone that has never pulled the branch — which is every clone, because
// nothing else here touches it — and the portal then says "0 deployed" over a
// card whose deploy is live. Wrong in the quiet direction, which is the bad one.
let published = new Set();
try {
  execFileSync('git', ['fetch', '-q', 'origin', 'gh-pages'], {
    cwd: ROOT, stdio: 'ignore', timeout: 25000,
  });
  const ls = execFileSync('git', ['ls-tree', '--name-only', 'FETCH_HEAD'], {
    cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
  });
  published = new Set(ls.trim().split('\n').map((s) => s.replace(/\/$/, '')));
} catch {
  console.log('  (gh-pages unreadable — deploy status unknown)');
}

const html = buildHub(REGISTER, {
  mode: 'portal',
  root: ROOT,
  isLive: (v) => published.has(v.slug),
  origin: ORIGIN,
  base: BASE,
});

writeFileSync(join(ROOT, 'index.html'), html);

console.log(`\n  index.html  —  ${REGISTER.variants.length} version(s)`);
for (const v of REGISTER.variants) {
  const shot = previewFor(ROOT, v.slug);
  const live = published.has(v.slug);
  console.log(`    ${v.slug.padEnd(22)} ${live ? 'deployed' : 'NOT DEPLOYED'}  ${shot ? '' : ' NO PREVIEW — npm run shoot'}`);
}
console.log('');
